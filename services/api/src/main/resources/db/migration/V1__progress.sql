-- Progress schema. Written to run unchanged on Postgres and on H2 (MODE=PostgreSQL).

create table xp_event (
    id          bigint generated by default as identity primary key,
    attempt_id  varchar(64)  not null,
    learner_id  varchar(64)  not null,
    kind        varchar(16)  not null,
    chapter_id  varchar(128) not null,
    item_id     varchar(128) not null,
    xp          integer      not null,
    score       float(53)    not null,
    occurred_at timestamp(6) with time zone not null,
    constraint uq_xp_event_attempt unique (attempt_id)  -- the idempotency guard
);
create index ix_xp_event_learner on xp_event (learner_id, occurred_at);

create table trap_entry (
    id             bigint generated by default as identity primary key,
    learner_id     varchar(64)   not null,
    chapter_id     varchar(128)  not null,
    item_id        varchar(128)  not null,
    kind           varchar(16)   not null,
    prompt         varchar(2000) not null,
    times_fallen   integer       not null,
    last_fallen_at timestamp(6) with time zone not null,
    cleared        boolean       not null,
    constraint uq_trap_item unique (learner_id, chapter_id, item_id)
);

create table flashcard_state (
    id         bigint generated by default as identity primary key,
    learner_id varchar(64)  not null,
    card_key   varchar(256) not null,
    box        integer      not null,
    due_on     date         not null,
    constraint uq_flashcard unique (learner_id, card_key)
);
